"""
数据画像（Data Profile）
=========================
把「领域知识」固化成可执行规则，这是自动化数据质检的核心。

为什么需要这个文件？
    数据质检最难的不是「发现异常」，而是「判断异常是不是 bug」。
    例如：1 星干员没有技能 —— 这不是解析器漏了，是游戏本来就如此。
    如果把这类"数据固有特性"当 bug 去修，会越改越错。

    这个文件的作用，就是把「哪些情况属于正常」写清楚，
    让诊断脚本能自动把它们和真正的解析 bug 区分开。

以后扩展新页面类型（关卡 / 敌人 / 道具）时，只需在这里追加规则。
"""

